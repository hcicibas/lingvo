export function getUIStrings(langCode: string): UIStrings {
  return translations[langCode] ?? translations.en;
}

export function interpolate(
  template: string,
  vars: Record<string, string>
): string {
  return template.replace(/\{(\w+)\}/g, (_, key) => vars[key] ?? "");
}
